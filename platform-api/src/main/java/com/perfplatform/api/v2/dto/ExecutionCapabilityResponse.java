package com.perfplatform.api.v2.dto;

import io.swagger.v3.oas.annotations.media.Schema;

/**
 * What this deployment will actually do when a run is triggered.
 *
 * <p>Exists so a consumer never has to infer it. A deployment configured with a provider that
 * generates no load produces runs that look, in every other respect, exactly like real ones — same
 * states, same timings, same shaped results. The only honest way to prevent someone acting on those
 * numbers is to tell them before they see any, in the interface they are already looking at.
 *
 * <p>Read by the console to render a permanent line in its header. Not a diagnostic endpoint and not
 * an admin one: the answer changes what a consumer should believe about every number on the screen.
 *
 * @param providerId       the configured execution provider, e.g. {@code fake}, {@code local-jmeter}
 * @param generatesRealLoad whether workloads it starts actually send traffic to the target. When
 *                         false, every run's measurements are invented and no objective can pass
 * @param summary          one sentence a consumer can act on, safe to display verbatim
 */
@Schema(description = "The execution provider this deployment is configured with, and whether it "
        + "generates real load")
public record ExecutionCapabilityResponse(
        String providerId,
        boolean generatesRealLoad,
        String summary) {

    /** What a deployment that generates no load tells its consumers. */
    private static final String SYNTHETIC_SUMMARY =
            "No load is generated. Runs complete with invented measurements that describe nothing, "
                    + "and every objective is reported as indeterminate.";

    public static ExecutionCapabilityResponse of(String providerId, boolean generatesRealLoad) {
        return new ExecutionCapabilityResponse(providerId, generatesRealLoad,
                generatesRealLoad
                        ? "Load is generated by the '" + providerId + "' provider and measurements "
                                + "describe real interactions with the target."
                        : SYNTHETIC_SUMMARY);
    }
}
