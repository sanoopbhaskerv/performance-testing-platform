-- V10: append-only recorder audit events.
--
-- A recording browser is a user-driven network client. Some sessions never become test runs, so
-- their security evidence cannot live in run_events. This table records who asked for a session,
-- what registered target it was tied to, which destinations were blocked, and what capture material
-- the sanitizer removed.

CREATE TABLE recorder_audit_events (
    sequence     BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    session_id   UUID          NOT NULL,
    team_id      UUID          NOT NULL,
    event_type   VARCHAR(48)   NOT NULL,
    actor        VARCHAR(255)  NOT NULL,
    detail       JSONB         NOT NULL DEFAULT '{}'::jsonb,
    occurred_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,

    CONSTRAINT pk_recorder_audit_events PRIMARY KEY (sequence),
    CONSTRAINT fk_recorder_audit_events_team FOREIGN KEY (team_id) REFERENCES teams (id)
);

CREATE INDEX ix_recorder_audit_events_session_sequence
    ON recorder_audit_events (session_id, sequence);

CREATE INDEX ix_recorder_audit_events_team_time
    ON recorder_audit_events (team_id, occurred_at DESC);

CREATE OR REPLACE FUNCTION reject_recorder_audit_event_mutation()
RETURNS TRIGGER AS $$
BEGIN
    RAISE EXCEPTION 'recorder_audit_events is append-only: event % of session % cannot be modified or deleted',
        OLD.sequence, OLD.session_id
        USING ERRCODE = 'integrity_constraint_violation';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_recorder_audit_events_no_update
    BEFORE UPDATE ON recorder_audit_events
    FOR EACH ROW
    EXECUTE FUNCTION reject_recorder_audit_event_mutation();

CREATE TRIGGER trg_recorder_audit_events_no_delete
    BEFORE DELETE ON recorder_audit_events
    FOR EACH ROW
    EXECUTE FUNCTION reject_recorder_audit_event_mutation();
